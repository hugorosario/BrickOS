import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, renameSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const COMPONENTS = Object.freeze(['mainui', 'inputd', 'osdd', 'ledd', 'tmenu', 'gameswitcher', 'uninstall', 'updater', 'setup', 'assets']);
export const NATIVE_COMPONENTS = Object.freeze({
  'mainui/MainUI': 'mainui', 'bin/trimui_inputd': 'inputd', 'bin/trimui_osdd': 'osdd',
  'bin/brickos-ledd': 'ledd', 'bin/libtmenu.so': 'tmenu',
  'gameswitcher/GameSwitcher': 'gameswitcher', 'gameswitcher/gs-session': 'gameswitcher',
  'gameswitcher/libtmenu.so': 'gameswitcher', 'uninstall/brickos-uninstall': 'uninstall',
  'updater/brickos-update': 'updater',
});
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
export function parseVersion(version) {
  if (typeof version !== 'string' || version.length > 63) throw new Error(`Invalid SemVer: ${version}`);
  const match = version.match(/^(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/);
  if (!match || match[0] !== version || match[4]?.split('.').some(id => /^0[0-9]+$/.test(id))) throw new Error(`Invalid SemVer: ${version}`);
  return { core: match.slice(1, 4).map(Number), pre: match[4]?.split('.') || [], build: match[5] || '' };
}
export function compareVersions(a, b) {
  const left = parseVersion(a), right = parseVersion(b);
  for (let i = 0; i < 3; ++i) if (left.core[i] !== right.core[i]) return Math.sign(left.core[i] - right.core[i]);
  if (!left.pre.length || !right.pre.length) return left.pre.length === right.pre.length ? 0 : left.pre.length ? -1 : 1;
  for (let i = 0; i < Math.max(left.pre.length, right.pre.length); ++i) {
    if (i >= left.pre.length) return -1;
    if (i >= right.pre.length) return 1;
    const x = left.pre[i], y = right.pre[i]; if (x === y) continue;
    const nx = /^[0-9]+$/.test(x), ny = /^[0-9]+$/.test(y);
    if (nx !== ny) return nx ? -1 : 1;
    if (nx && x.length !== y.length) return Math.sign(x.length - y.length);
    return x < y ? -1 : 1;
  }
  return 0;
}
export function validateConfig(value) {
  if (!value || value.schema !== 1 || Object.keys(value).sort().join() !== 'components,release,schema') throw new Error('Invalid versions.json schema');
  parseVersion(value.release);
  if (!value.components || Object.keys(value.components).sort().join() !== [...COMPONENTS].sort().join()) throw new Error('Missing or unknown component');
  for (const id of COMPONENTS) parseVersion(value.components[id]);
  return value;
}
export function loadConfig(root = ROOT) { return validateConfig(JSON.parse(readFileSync(resolve(root, 'versions.json'), 'utf8'))); }
export function generatedHeader(config, bytes) {
  return `// Generated by tools/component-versions.mjs; edit versions.json instead.\n#ifndef BRICKOS_GENERATED_VERSIONS_H\n#define BRICKOS_GENERATED_VERSIONS_H\n#define BRICKOS_VERSIONS_SOURCE_SHA256 "${sha256(bytes)}"\n#define BRICKOS_RELEASE_VERSION "${config.release}"\n${COMPONENTS.map(id => `#define BRICKOS_VERSION_${id.toUpperCase()} "${config.components[id]}"`).join('\n')}\n#endif\n`;
}
export function checkGenerated(root = ROOT) {
  const bytes = readFileSync(resolve(root, 'versions.json')), config = validateConfig(JSON.parse(bytes));
  if (readFileSync(resolve(root, 'src/common/versions.generated.h'), 'utf8') !== generatedHeader(config, bytes))
    throw new Error('Component version header is stale; run node tools/component-versions.mjs generate');
  return config;
}
export function nativeMetadata(id, version) { return Buffer.from(`BrickOS ComponentVersion/1\ncomponent=${id}\nversion=${version}\n\0`); }
export function readNativeMetadata(bytes) {
  const marker = Buffer.from('BrickOS ComponentVersion/1\n');
  const at = bytes.indexOf(marker);
  if (at < 0 || bytes.indexOf(marker, at + marker.length) >= 0) throw new Error('Missing or ambiguous native component version');
  const end = bytes.indexOf(0, at);
  const match = end >= at && bytes.subarray(at, end).toString().match(/^BrickOS ComponentVersion\/1\ncomponent=([a-z]+)\nversion=([^\n]+)\n$/);
  if (!match || !COMPONENTS.includes(match[1])) throw new Error('Malformed native component version');
  parseVersion(match[2]); return { component: match[1], version: match[2] };
}
export function componentForPath(path) {
  if (NATIVE_COMPONENTS[path]) return NATIVE_COMPONENTS[path];
  if (path.startsWith('mainui/')) return 'mainui';
  if (path.startsWith('gameswitcher/')) return 'gameswitcher';
  if (path.startsWith('uninstall/')) return 'uninstall';
  if (path.startsWith('updater/')) return 'updater';
  for (const id of ['inputd', 'osdd', 'ledd', 'tmenu'])
    if (path === `helpers/${id}-install.sh` || path.startsWith(`templates/brickos-${id}-`)) return id;
  if (path === 'setup.sh' || path === '../../../System/starts/brickos-00-setup.sh') return 'setup';
  if (/^(bootlogos|splashscreens|loading-screens|icons\/settings|wallpapers)\//.test(path)) return 'assets';
  throw new Error(`No component owns package path ${path}`);
}
export function componentManifest(files, config) {
  validateConfig(config);
  const components = Object.fromEntries(COMPONENTS.map(id => [id, { version: config.components[id], files: [] }]));
  for (const file of files) {
    const id = componentForPath(file.path);
    if (NATIVE_COMPONENTS[file.path]) {
      const embedded = readNativeMetadata(file.bytes);
      if (embedded.component !== id || embedded.version !== config.components[id]) throw new Error(`${file.path}: stale or wrong component version; rebuild ${id}`);
    }
    components[id].files.push({ path: file.path, sha256: sha256(file.bytes), size: file.bytes.length, mode: file.mode });
  }
  for (const id of COMPONENTS) {
    const rows = components[id].files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
    if (!rows.length) throw new Error(`Component ${id} has no package files`);
    components[id].fingerprint = sha256(Buffer.from(JSON.stringify(rows)));
  }
  return { schema: 1, release: config.release, components };
}
export function compareManifests(previous, next) {
  for (const doc of [previous, next]) {
    if (doc?.schema !== 1 || Object.keys(doc.components || {}).sort().join() !== [...COMPONENTS].sort().join()) throw new Error('Invalid component manifest');
    parseVersion(doc.release);
    for (const id of COMPONENTS) {
      parseVersion(doc.components[id].version);
      if (!/^[a-f0-9]{64}$/.test(doc.components[id].fingerprint)) throw new Error(`Invalid fingerprint for ${id}`);
    }
  }
  if (compareVersions(next.release, previous.release) <= 0) throw new Error('Release version must increase');
  return COMPONENTS.map(id => {
    const before = previous.components[id], after = next.components[id];
    const changed = before.fingerprint !== after.fingerprint, order = compareVersions(after.version, before.version);
    if (order < 0 || (changed && order === 0)) throw new Error(`${id}: changed payload needs a newer component version`);
    return { component: id, from: before.version, to: after.version, changed };
  });
}
function atomic(path, text) {
  const temporary = `${path}.${process.pid}.tmp`; writeFileSync(temporary, text); renameSync(temporary, path);
}
function generate(root) {
  const bytes = readFileSync(resolve(root, 'versions.json')), config = validateConfig(JSON.parse(bytes));
  atomic(resolve(root, 'src/common/versions.generated.h'), generatedHeader(config, bytes));
}
export function main(args = process.argv.slice(2), root = ROOT) {
  const [command = 'list', id, level] = args, config = loadConfig(root);
  if (command === 'list') { console.log(JSON.stringify(config, null, 2)); return; }
  if (command === 'check') { checkGenerated(root); console.log('Component versions and generated header agree.'); return; }
  if (command === 'generate') { generate(root); return; }
  if (command === 'inspect') {
    console.log(JSON.stringify(readNativeMetadata(readFileSync(resolve(root, id))), null, 2)); return;
  }
  if (command === 'compare') {
    const previous = JSON.parse(readFileSync(resolve(root, id))), next = JSON.parse(readFileSync(resolve(root, level)));
    console.table(compareManifests(previous, next)); return;
  }
  if (command === 'bump' || command === 'set') {
    if (id !== 'release' && !COMPONENTS.includes(id)) throw new Error('Choose release or a component id');
    const current = id === 'release' ? config.release : config.components[id];
    let next = level;
    if (command === 'bump') {
      const index = ['major', 'minor', 'patch'].indexOf(level); if (index < 0) throw new Error('Choose major, minor or patch');
      const core = parseVersion(current).core; ++core[index]; for (let i = index + 1; i < 3; ++i) core[i] = 0; next = core.join('.');
    }
    parseVersion(next); if (compareVersions(next, current) <= 0) throw new Error('The version must increase');
    if (id === 'release') config.release = next; else config.components[id] = next;
    atomic(resolve(root, 'versions.json'), JSON.stringify(config, null, 2) + '\n'); generate(root);
    console.log(`${id}: ${current} -> ${next}`); return;
  }
  throw new Error('usage: component-versions.mjs list|generate|check|bump ID major|minor|patch|set ID VERSION|inspect ELF|compare OLD.json NEW.json');
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
